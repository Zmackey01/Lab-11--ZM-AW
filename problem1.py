def string_to_char_dict(string):
  """
  string -> dictionary

  takes a string of text and returns a dictionary mapping each unique character to the number of times it appears.

  >>> string_to_char_dict("aaaaaa")
  {'a': 6}
  >>> string_to_char_dict("abaaaab")
  {'a': 5, 'b': 2}
  """
